# 各面（切り取り線）を描画
for face_index, face in enumerate(faces):
    default_color = 'r-'
    special_color = 'b-'
    for i in range(len(face)):
        # 辺を構成する2つの頂点のインデックスを取得
        p1_index = face[i]
        p2_index = face[(i + 1) % len(face)] # % len(face) でリストの最後に到達したら最初に戻る
        # 2つの頂点の座標を取得
        p1 = vertices[p1_index]
        p2 = vertices[p2_index]
        ax.plot([p1[0], p2[0]], [p1[1], p2[1]], default_color, linewidth=1)
        
line_color = 'b-'
