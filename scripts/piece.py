# --- 1. データの解析 (Parsing) ---
vertices = []
faces = []
lines = []

# データを1行ずつ処理
for line in obj_data.strip().split('\n'):
    parts = line.split()
    if not parts:
        continue

    # 頂点データ (v) を抽出
    if parts[0] == 'v':
        vertices.append((float(parts[1]), float(parts[2])))

    # 面データ (f) を抽出
